#!/usr/bin/env sh
# Створює головний ключ шифрування для локального сервера (один раз): 32 випадкові байти у файлі secrets/private_store_master_key.
# Без цього ключа зашифровані дані відновити НЕМОЖЛИВО: збережіть копію окремо (менеджер паролів, сейф).
set -eu
root="$(cd "$(dirname "$0")/.." && pwd)"
file="$root/secrets/private_store_master_key"
if [ -f "$file" ]; then
  echo "Головний ключ уже є ($file) - не перезаписую."
  exit 0
fi
mkdir -p "$root/secrets"
chmod 700 "$root/secrets"
umask 077
head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' > "$file"
# Контейнер працює від користувача 10001: файл має бути читабельним для нього, але не для інших користувачів системи.
chmod 440 "$file" 2>/dev/null || true
echo
echo "Створено головний ключ: $file"
echo "ВАЖЛИВО: збережіть КОПІЮ цього файлу окремо від комп'ютера (менеджер паролів, сейф)."
echo "Без нього дані на локальному сервері не відновити - і ніхто, включно зі Studio, не зможе допомогти."
