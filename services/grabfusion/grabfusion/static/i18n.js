const GRAB_LANGUAGE_KEY = 'gf_language';
let grabLanguage = 'uk';
try {
  if ((localStorage.getItem(GRAB_LANGUAGE_KEY) || localStorage.getItem('nova_language')) === 'en') grabLanguage = 'en';
} catch (e) { /* Storage may be unavailable in private browsing. */ }

function tr(text, ...args) {
  if (typeof text !== 'string') return text;
  const message = grabLanguage === 'en' && Object.hasOwn(GRAB_EN, text) ? GRAB_EN[text] : text;
  return args.length ? message.replace(/\{(\d+)\}/g, (match, index) => args[index] === undefined ? match : String(args[index])) : message;
}

function applyGrabLanguage() {
  document.documentElement.lang = grabLanguage;
  document.getElementById('app-manifest').setAttribute('href', grabLanguage === 'en' ? 'manifest.webmanifest?lang=en' : 'manifest.webmanifest');
  for (const node of document.querySelectorAll('[data-translate]')) {
    const source = node.dataset.translate || node.textContent;
    node.dataset.translate = source;
    node.textContent = tr(source);
  }
  for (const node of document.querySelectorAll('[data-translate-label]')) {
    node.setAttribute('aria-label', tr(node.dataset.translateLabel));
  }
  const toggle = document.getElementById('btn-language');
  const next = grabLanguage === 'uk' ? 'en' : 'uk';
  const label = next === 'en' ? 'Switch to English' : 'Перемкнути на українську';
  toggle.textContent = next === 'en' ? 'EN' : 'UA';
  toggle.lang = next;
  toggle.setAttribute('aria-label', label);
}

function toggleGrabLanguage() {
  grabLanguage = grabLanguage === 'uk' ? 'en' : 'uk';
  try { localStorage.setItem(GRAB_LANGUAGE_KEY, grabLanguage); } catch (e) { /* Still switch for this visit. */ }
  applyGrabLanguage();
}

