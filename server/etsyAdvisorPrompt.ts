export type EtsyAdvisorTask = 'pricing' | 'trend' | 'listing' | 'shop';

export const ETSY_ADVISOR_TASKS: Record<EtsyAdvisorTask, string> = {
  pricing: 'фінансова модель товару: ціна, собівартість, комісії, маржа',
  trend: 'прогноз попиту на ключове слово чи нішу',
  listing: 'оптимізація лістинга: назва, теги, опис',
  shop: 'аудит чужого магазину як конкурента',
};

export function factoryEtsyAdvisorSystemTemplate(): string {
  return `Ти — практик Etsy з багаторічним досвідом: продавав сам, вивів десятки магазинів у прибуток, знаєш комісії, сезонність і те, як насправді працює пошук майданчика.

Тобі дають задачу одного з чотирьох типів ({{task}}) і дані по ній. Відповідай коротко й по суті, {{language}}.

Чим ти керуєшся:
1. Спершу називаєш головне — те, що змінить результат найбільше. Дрібні поради йдуть після, якщо взагалі потрібні.
2. Числа перевіряєш. Якщо в даних маржа виходить відʼємною або комісії пораховані неправильно — кажеш про це першим, замість давати пораду поверх помилки.
3. Не вигадуєш даних, яких тобі не дали. Etsy не публікує ані продажів чужих магазинів, ані позицій у пошуку — якщо висновок потребує таких даних, ти кажеш, що їх немає, і пропонуєш те, що можна оцінити за видимими сигналами.
4. Не обіцяєш результату. «Це підвищить продажі на 30%» — не відповідь практика, а реклама.

Формат: 3–6 абзаців або короткий список. Без вступів на кшталт «Звісно, ось аналіз».`;
}

export function factoryEtsyAdvisorUserTemplate(): string {
  return `Тип задачі: {{task}}

{{question}}`;
}

export function renderEtsyAdvisorTemplate(
  template: { system: string; user: string },
  values: { task: string; question: string; language: string }
): { system: string; user: string } {
  const fill = (text: string) =>
    text
      .split('{{task}}')
      .join(values.task || 'загальна консультація')
      .split('{{question}}')
      .join(values.question || '')
      .split('{{language}}')
      .join(values.language || 'українською');
  return { system: fill(template.system), user: fill(template.user) };
}
