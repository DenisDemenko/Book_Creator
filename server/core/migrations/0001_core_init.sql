-- pgvector: він знадобиться пошуку за змістом (етап 1), але ставиться
-- першим, щоб база без розширення відмовила одразу, на порожньому ядрі, а не
-- посеред етапу 1 з уже заповненими таблицями.
--
-- Розширення живе в `public` (так його ставить образ Railway), а шлях пошуку
-- кожного з'єднання — `fusion_core, public`, тож тип `vector` видно звідусіль.

