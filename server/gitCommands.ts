/**
 * Каталог git-операцій над вибраним комітом — для панелі в адмінці.
 *
 * Постановка власника: «десять найуживаніших функцій, які можна виконувати
 * над комітами, кнопками, з вибором номера коміта або введенням вручну, і
 * підказкою при наведенні мишкою, що саме команда робить».
 *
 * ЧОМУ КАТАЛОГ — ДАНІ, А НЕ КОД. Кожна команда описана тут рядками, і
 * жоден із цих рядків не склеюється в команду оболонки: `args` — це вже
 * готовий СПИСОК аргументів для `execFile`, а `%H` у ньому замінюється на
 * перевірений хеш. Тому каталог можна тестувати окремо від виконання, і
 * тест справді перевіряє те, що поїде в git.
 *
 * ДВІ ОСІ, А НЕ ОДНА — і межа виконання на СЕРВЕРІ, не в кнопках.
 *
 * Рівень (`tier`) відповідає на «чи виконує це панель»:
 *  - `read`   — нічого не змінює: показати, порівняти, перелічити;
 *  - `add`    — створює новий об'єкт (коміт-відкат, теґ, гілку), історію
 *               НЕ переписує, тож будь-яку дію легко відкотити;
 *  - `manual` — панель лише готує команду, запускає власник у терміналі.
 *
 * Небезпека (`danger`) — окрема ознака: незворотно знищує роботу. Осі
 * справді різні: `git checkout <хеш>` панель не виконує (`manual`), але
 * небезпечним він не є — лише відчіпляє HEAD. Спершу я звалив це в один
 * рівень `rewrite`, і тест справедливо впав на підказці, яка не мала
 * права починатися словом «НЕБЕЗПЕЧНО».
 *
 * Команди рівня `manual` сервер НЕ ВИКОНУЄ взагалі — навіть на прямий
 * запит із підробленим тілом. Причин дві, і обидві практичні, а не боязкі:
 *  1. панель відкрита будь-кому з адмінською сесією, а один помилковий
 *     клік по `reset --hard` знищує незакомічену роботу назавжди;
 *  2. `reset`, `rebase` і `squash` майже завжди впираються в конфлікти, а
 *     конфлікт із веб-панелі не розв'язати — все одно потрібен термінал.
 *
 * МЕРЕЖІ ТУТ НЕМА СВІДОМО. Жодна команда не звертається до remote:
 * `push`, `fetch` і `pull` до приватного репозиторію попросили б логін і
 * повісили серверний процес до таймауту. Пуш робить власник сам — так у
 * цьому проєкті влаштовано від початку (див. журнал).
 */

/**
 * Рівень = ЧИ ВИКОНУЄ це панель. Небезпека — окрема ознака (`danger`).
 *
 * Спершу тут був один рівень `rewrite` на всі команди, які панель не
 * виконує, — і тест справедливо впав: `git checkout <хеш>` історію НЕ
 * переписує, він лише відчіпляє HEAD. Виконувати його з панелі все одно
 * не варто (повертатись треба окремою командою), але називати
 * небезпечним — брехня. Тому дві осі:
 *
 *  - `read` / `add` — панель виконує;
 *  - `manual`       — панель лише готує команду, запускає власник;
 *  - `danger: true` — незворотно знищує роботу; малюється червоним.
 */
export type GitCommandTier = 'read' | 'add' | 'manual';

export interface GitCommandSpec {
  id: string;
  /** Підпис на кнопці. */
  label: string;
  /** Сама команда — так, як власник набрав би її в терміналі. */
  display: string;
  /**
   * Що саме вона робить — текст підказки при наведенні. Пишеться так,
   * щоб відповідати на питання «а що буде, якщо я це натисну», а не
   * переказувати назву команди іншими словами.
   */
  tooltip: string;
  tier: GitCommandTier;
  /** Незворотно знищує роботу — окремо від того, чи виконує панель. */
  danger?: boolean;
  /**
   * Аргументи для `execFile('git', …)`. `%H` → перевірений хеш коміта,
   * `%ARG` → перевірене ім'я (теґа чи гілки). Порожньо для команд, які
   * сервер не виконує.
   */
  args: string[];
  /** Чи потрібне ім'я від власника (теґ, гілка). */
  needsName?: boolean;
  /** Підпис поля для імені. */
  namePlaceholder?: string;
  /**
   * Чи вимагати чистого робочого дерева. Для `revert` і `cherry-pick` —
   * так: при конфлікті вони лишають репозиторій у півстані, і якщо там
   * була незакомічена робота власника, вона змішається з конфліктом.
   */
  needsCleanTree?: boolean;
  /** Команда, якою вийти з півстану, якщо виник конфлікт. */
  abortHint?: string;
}

