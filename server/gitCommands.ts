/**
 * Чи потрібен цій команді вибраний коміт.
 *
 * ВИВОДИТЬСЯ з того, чи команда справді згадує хеш (`%H` в аргументах або
 * `<хеш>` у показі), а не оголошується окремим полем. Інакше `git tag
 * <ім'я> <хеш>` і `git branch <ім'я> <хеш>`, яким потрібні ОБА аргументи,
 * не вміщались би в одне поле `needs` — і одне з двох тихо загубилось би.
 */
export function needsCommit(spec: GitCommandSpec): boolean {
  return spec.args.some((a) => a.includes('%H')) || spec.display.includes('<хеш>');
}

/**
 * Префікс до кожного виклику git.
 *
 * `core.quotepath=false` — щоб імена файлів із кирилицею виводились
 * читабельно. Без нього git екранує кожен не-ASCII байт вісімкою, і
 * `нове.txt` приїжджає в панель як `"\320\275\320\276\320\262\320\265.txt"`.
 * Знайшлось на тесті, який навмисне взяв кириличне ім'я файлу; на
 * латиниці баг не видно зовсім.
 */
export const GIT_PREFIX_ARGS = ['-c', 'core.quotepath=false'];

/** Пошук за id. */
export function commandById(id: string): GitCommandSpec | undefined {
  return GIT_COMMANDS.find((c) => c.id === id);
}

/**
 * Підставляє хеш та ім'я в СПИСОК аргументів.
 *
 * Заміна робиться по цілому елементу списку або в його середині, але
 * список лишається списком: нове значення не може «розклеїтись» на два
 * аргументи чи внести прапорець, бо `execFile` передає масив у процес як
 * є, без оболонки.
 */
export function buildArgs(spec: GitCommandSpec, hash: string, name?: string): string[] {
  return spec.args.map((a) => a.replace('%H', hash).replace('%ARG', name ?? ''));
}

/**
 * Заповнювачі в показі команди — по одному на тип аргумента.
 *
 * Тримаються тут, а не в клієнті, з тієї ж причини, що й підказки: дві
 * копії однакових рядків неминуче розійдуться, а розійшовшись, панель
 * почала б показувати одну команду, а виконувати іншу.
 */
export const ARG_PLACEHOLDER: Record<GitArgKind, string> = {
  none: '',
  commit: '<хеш>',
  path: '<шлях>',
  ref: '<ім’я>',
  message: '<опис>',
  url: '<адреса>',
};

/** Готова команда для показу й копіювання — з підставленими значеннями. */
export function renderDisplay(spec: GitCommandSpec, hash: string, name?: string): string {
  let out = spec.display.replace('<хеш>', hash || '<хеш>');
  const token = ARG_PLACEHOLDER[spec.needs || 'none'];
  const value = name && name.trim() ? name.trim() : '';
  if (token && value) out = out.replace(token, value);
  return out;
}

/**
 * Ім'я теґа чи гілки, яке ми готові передати git.
 *
 * Окрема перевірка ПЕРЕД `git check-ref-format`: та відсіює некоректні
 * посилання, але нам треба відсіяти ще й те, що коректне як ref, проте
 * небажане як аргумент — насамперед рядки, що починаються з `-`, бо git
 * прийняв би їх за прапорець.
 */
export function isSafeRefName(name: string): boolean {
  if (!name || name.length > 100) return false;
  if (name.startsWith('-')) return false;
  if (name.startsWith('/') || name.endsWith('/')) return false;
  if (name.endsWith('.') || name.endsWith('.lock')) return false;
  if (name.includes('..') || name.includes('@{')) return false;
  // Латиниця, цифри і небагато розділювачів; слеш дозволено для fix/…
  return /^[A-Za-z0-9._/-]+$/.test(name);
}

/**
 * Шлях до файлу, який ми готові передати git.
 *
 * Це найновіша поверхня для помилок у цій панелі, тож відмовляємо на
 * кожній окремій підставі, а не однією загальною перевіркою:
 *  - `-` на початку git прочитав би як прапорець;
 *  - `..` виводить за межі репозиторію;
 *  - абсолютний шлях (і `C:\…`) взагалі не про цей репозиторій;
 *  - NUL Node.js не дає передати в процес — упав би сам запуск.
 *
 * Остаточну перевірку «чи всередині репозиторію» робить маршрут: тут
 * немає доступу до файлової системи, і вдавати, що є, не варто. Плюс усі
 * шляхові команди передають шлях ПІСЛЯ `--`, тож навіть дозволений рядок
 * не може бути прочитаний як ревізія.
 */
export function isSafePath(p: string): boolean {
  if (!p || p.length > 400) return false;
  if (p.startsWith('-')) return false;
  if (p.includes('\u0000')) return false;
  if (p.startsWith('/') || /^[A-Za-z]:[\\/]/.test(p)) return false;
  // Розділювачі нормалізуємо до `/`, щоб `..\..` не проліз повз перевірку.
  const parts = p.replace(/\\/g, '/').split('/');
  if (parts.some((seg) => seg === '..')) return false;
  return true;
}

/**
 * Повідомлення коміта. Оболонки немає, тож лапки й зірочки безпечні — але
 * порожній опис і керуючі символи ні до чого, а межу довжини ставимо, щоб
 * у журнал не поїхало півфайлу.
 */
export function isSafeMessage(m: string): boolean {
  if (!m || !m.trim() || m.length > 2000) return false;
  // eslint-disable-next-line no-control-regex
  return !/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(m);
}

/** Хеш, який ми готові навіть показувати git для перевірки. */
export function isPlausibleHash(hash: string): boolean {
  return /^[0-9a-fA-F]{7,40}$/.test(hash);
}
