/**
 * Спільний контракт рушіїв PDF.
 *
 * ЧОМУ ЦЕ ЗʼЯВИЛОСЬ. Досі PDF робив один рушій — власний, на `pdf-lib`. Він
 * дає те, чого не дає жоден інший: точний контроль полів під KDP (дзеркальні
 * поля, корінець за кількістю сторінок) і нульову вагу образу. Але він же
 * означає, що вигляд книги визначає НАШ код, а не письменник: щоб змінити
 * типографіку, треба міняти `pdfRenderer.ts`.
 *
 * Власник вибрав інший підхід: рушій — це вибір автора, як шрифт чи формат.
 * Звідси цей інтерфейс. Чотири рушії, і кожен сильний у своєму:
 *
 *   nova      — pdf-lib. Точність під KDP, миттєвий, нічого не потребує.
 *   chromium  — HTML + CSS через headless-браузер. Виглядом керує таблиця
 *               стилів, тобто автор (і ми) може змінити верстку, не чіпаючи
 *               код рендера.
 *   pandoc    — pandoc + XeLaTeX із шаблоном Eisvogel. Справжня книжкова
 *               типографіка: переноси, лігатури, microtype.
 *   gamma     — зовнішній сервіс, який уже вбудований (записи #96–#99).
 *
 * ГОЛОВНЕ В ЦЬОМУ ФАЙЛІ — `available()`, а не `render()`.
 *
 * Три з чотирьох рушіїв залежать від того, чого може не бути: бінарника в
 * образі, ключа, мережі. Якщо про недоступність дізнаватись у момент
 * публікації, автор натисне «Опублікувати», почекає й отримає помилку — а
 * втратить при цьому не хвилину, а довіру до всієї публікації. Тому кожен
 * рушій зобовʼязаний уміти сказати ДО натискання, чи він працює і чому ні,
 * українською й конкретно («немає pandoc в образі»), а не «недоступно».
 */

import type { PdfBookInput, PdfLayoutSpec } from '../pdfTypes';

export type PdfEngineId = 'nova' | 'chromium' | 'pandoc' | 'gamma';

export const PDF_ENGINE_IDS: readonly PdfEngineId[] = ['nova', 'chromium', 'pandoc', 'gamma'];

/** Рушій за замовчуванням: єдиний, який не залежить ні від чого зовнішнього. */
export const DEFAULT_PDF_ENGINE: PdfEngineId = 'nova';

/**
 * Що саме друкуємо. Книга й курс верстаються однаково — різниця лише в
 * тому, звідки взявся текст, — тож рушій про це знати не мусить.
 */
export type PdfDocumentKind = 'book' | 'course';

export interface PdfRenderRequest {
  /** Мінімальний зріз книги — той самий, який приймає власний рушій. */
  book: PdfBookInput;
  kind: PdfDocumentKind;
  /**
   * Макет. Власний рушій виконує його точно; зовнішні беруть із нього те,
   * що вміють (формат сторінки, поля, кегль), і це не приховується: див.
   * `honoredSpec` у результаті.
   */
  spec?: Partial<PdfLayoutSpec>;
  /** Друкована редакція під KDP. Підтримує лише рушій `nova`. */
  print?: boolean;
  /** Хто друкує — для рушіїв, які працюють під ключем автора (gamma). */
  ownerId?: string | null;
  /** Роль того, хто друкує: від неї залежить, чий ключ Gamma застосовний. */
  ownerRole?: string | null;
  /** Тема оформлення для рушіїв, які мають кілька виглядів. */
  theme?: string;
}

export interface PdfRenderResult {
  bytes: Uint8Array;
  pageCount: number;
  engineId: PdfEngineId;
  /**
   * ЧЕСНІСТЬ ПРО МАКЕТ. `false` означає: рушій зверстав по-своєму, і
   * надісланий макет виконано лише частково. Автор має бачити це в
   * інтерфейсі, інакше він шукатиме в налаштуваннях причину, якої там немає.
   */
  honoredSpec: boolean;
  /** Що саме рушій зробив інакше. Порожньо — значить, нічого. */
  notesUk: string[];
}

/**
 * Дія, якою автор може зарадити САМ, — машиночитано.
 *
 * `fixUk` пояснює людині, що робити, але інтерфейсу з цього тексту нічого не
 * витягти: щоб відрізнити «підключіть свою підписку» (автор натисне й
 * підключить) від «немає pandoc в образі» (авторові тут робити нічого),
 * довелось би розбирати рядок або писати `if (engine.id === 'gamma')` — тобто
 * рівно те розповзання назв рушіїв по коду, проти якого існує реєстр.
 *
 * Тому намір називається окремим полем. Інтерфейс зіставляє дію з вікном,
 * яке її виконує, і про назви рушіїв так само не знає.
 */
export type PdfEngineFixAction = 'connect_gamma_key';

export interface PdfEngineAvailability {
  ok: boolean;
  /** Чому не працює — конкретно й українською. Порожньо, коли ok. */
  reasonUk?: string;
  /** Що зробити, щоб запрацював: «встановити pandoc», «додати ключ». */
  fixUk?: string;
  /**
   * Заповнюється ЛИШЕ тоді, коли зарадити може сам автор. Відсутність поля —
   * це теж відповідь: «полагодити звідси не можна», і кнопка лишається
   * вимкненою, а не веде у вікно, яке нічого не змінить.
   */
  fixAction?: PdfEngineFixAction;
}

/**
 * Контекст перевірки доступності.
 *
 * Потрібен, бо «доступний» — не властивість образу, а властивість ПАРИ
 * «рушій + автор»: pandoc або є в контейнері, або немає, а Gamma працює
 * рівно тоді, коли САМЕ ЦЕЙ автор підключив свою підписку. Без контексту
 * довелось би або показувати Gamma доступною всім, або ховати її від усіх.
 */
export interface PdfEngineContext {
  ownerId?: string | null;
  ownerRole?: string | null;
}

export interface PdfEngine {
  id: PdfEngineId;
  label: string;
  /** Одне речення для автора: у чому саме цей рушій сильніший за інші. */
  strengthUk: string;
  /** Чого він НЕ вміє. Пишеться так само обовʼязково, як і сильний бік. */
  limitUk: string;
  /** Чи підтримує друковану редакцію під KDP. */
  supportsPrint: boolean;
  available(context?: PdfEngineContext): Promise<PdfEngineAvailability>;
  render(request: PdfRenderRequest): Promise<PdfRenderResult>;
}

/**
 * Помилка рендера з причиною, придатною для показу авторові.
 *
 * `kind` окремо від тексту, бо реакція різна: `unavailable` — запропонувати
 * інший рушій, `timeout` — спробувати ще раз або спростити книгу,
 * `bad_input` — виправити текст, `engine` — наша справа, не автора.
 */
export class PdfEngineError extends Error {
  constructor(
    readonly engineId: PdfEngineId,
    readonly kind: 'unavailable' | 'timeout' | 'bad_input' | 'engine',
    message: string
  ) {
    super(message);
    this.name = 'PdfEngineError';
  }
}
