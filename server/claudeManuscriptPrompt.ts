/**
 * Промпт «Форматування готового файлу під Amazon KDP» — винесено з
 * claudeManuscript.ts у чистий файл за принципом manuscriptImagePrompt.ts.
 *
 * Відрізняється від решти модулів «Ядра AI» двома речами:
 *   • system-промпт вимагає від моделі повернути СУВОРИЙ JSON
 *     (`{"chapters":[...],"notes":[...]}`) — ця схема лишається жорсткою в
 *     коді (Ядро AI показує її як readonly-текст, не редаговану);
 *   • user-промпт несе на собі ВЕСЬ РУКОПИС цілком (до 400 000 символів) —
 *     не метадані книги, а сам текст. Плейсхолдер {РУКОПИС} у «Ядрі AI»
 *     підставляється тестовим фрагментом, який адмін вставляє вручну.
 */

export interface ClaudeManuscriptPromptValues {
  bookTitle?: string;
  author?: string;
  genre?: string;
  /** Текст рукопису — у продакшн-виклику повний (до 400 000 символів), у «Ядрі AI» тестовий фрагмент. */
  manuscriptText: string;
}

/**
 * Системна інструкція. Частина з форматом JSON-відповіді (з рядка
 * «Поверни ЛИШЕ JSON…») — жорсткий контракт, не редагується в конструкторі
 * (Ядро AI показує її readonly), решта — редагований текст.
 */
export function factoryClaudeManuscriptSystemTemplate(): string {
  return [
    'Ти — досвідчений літературний верстальник і редактор, який готує готові рукописи до публікації ' +
      'в паперовому вигляді через Amazon KDP (Kindle Direct Publishing). Тобі присилають уже написаний ' +
      'текст книги — твоє завдання НЕ переписувати зміст, а лише структурувати й очистити форматування:\n' +
      '1. Визнач межі глав (за заголовками на кшталт «Глава 1», «Розділ перший», номерами, або за смисловими розривами, якщо явних заголовків нема) і дай кожній главі стислу назву українською, якщо в тексті її не було.\n' +
      '2. Прибери артефакти форматування: зайві порожні рядки (більше одного підряд), символи табуляції на початку абзаців, подвійні пробіли, невірні лапки (заміни на українські «лапки-ялинки»), зайві пробіли перед розділовими знаками.\n' +
      '3. НЕ додавай, не скорочуй і не перефразовуй авторський текст. Зберігай кожне речення як є — лише прибирай технічне сміття форматування.\n' +
      '4. Абзаци всередині глави розділяй одним порожнім рядком (\\n\\n).\n' +
      '5. Якщо в тексті є щось, що ти не певен як структурувати (наприклад, незрозуміло де межа глави, чи є розділ без назви, дивні символи, що могли бути помилкою конвертації), опиши це в полі notes — українською, коротко, по одному реченню на пункт.',
    '⚠️ ЖОРСТКИЙ КОНТРАКТ ВІДПОВІДІ (не редагується в конструкторі промтів):\n' +
      'Поверни ЛИШЕ JSON без жодного тексту навколо, у форматі:\n' +
      '{"chapters":[{"title":"Назва глави","text":"Очищений текст глави з абзацами через \\n\\n"}],"notes":["Спостереження 1","Спостереження 2"]}',
  ].join('\n\n');
}

/** Заводський шаблон user-промту — {РУКОПИС} несе повний текст книги (або тестовий фрагмент у «Ядрі AI»). */
export function factoryClaudeManuscriptUserTemplate(): string {
  return (
    'Книга: «{НАЗВА_КНИГИ}»{АВТОР}{ЖАНР}.\n\n' +
    'ВИХІДНИЙ ТЕКСТ РУКОПИСУ (форматуй за інструкціями в system prompt, поверни лише JSON):\n"""{РУКОПИС}"""'
  );
}

/** Підставляє значення. {АВТОР}/{ЖАНР} — інлайн-клаузи (не окремі абзаци): весь user-промпт — одне речення метаданих + текст. */
export function renderClaudeManuscriptUserTemplate(template: string, values: ClaudeManuscriptPromptValues): string {
  return template
    .replace('{НАЗВА_КНИГИ}', values.bookTitle?.trim() || 'без назви')
    .replace('{АВТОР}', values.author?.trim() ? `, автор: ${values.author.trim()}` : '')
    .replace('{ЖАНР}', values.genre?.trim() ? `, жанр: ${values.genre.trim()}` : '')
    .replace('{РУКОПИС}', values.manuscriptText || '');
}

/** Заводська поведінка (без адмінського шаблону) — точна копія колишньої buildUserPrompt/buildSystemPrompt із claudeManuscript.ts. */
export function buildClaudeManuscriptPrompt(values: ClaudeManuscriptPromptValues): { system: string; user: string } {
  return {
    system: factoryClaudeManuscriptSystemTemplate(),
    user: renderClaudeManuscriptUserTemplate(factoryClaudeManuscriptUserTemplate(), values),
  };
}
