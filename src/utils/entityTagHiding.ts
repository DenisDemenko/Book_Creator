/**
 * Арифметика позицій для РЕЖИМУ ПРИХОВУВАННЯ сутностей — чиста логіка,
 * виокремлена з `manuscriptEditor/EntityTagPlugin.ts`, щоб її можна було
 * юніт-тестити без TipTap-редактора (той самий підхід, що й у
 * `slashTrigger.ts`).
 *
 * НАВІЩО ЦЕ ВЗАГАЛІ. Коли автор натискає «Сховати сутності», Студія ховає не
 * лише колір: з канви зникає САМ ТЕГ, щоб лишився тільки текст книги. Ховає
 * його декорація ProseMirror (`display: none`), а текст документа при цьому
 * не змінюється — тобто прихований тег ФІЗИЧНО лишається в документі, і
 * курсор може в нього зайти:
 *
 *   • клік поруч із початком абзацу ставить каретку ВСЕРЕДИНУ тега;
 *   • стрілка ← може перевести її через увесь прихований тег;
 *   • набраний символ тоді лягає в середину `[/character:Олена]` і робить із
 *     нього `[/charXacter:Олена]` — а оскільки тег прихований, автор цього не
 *     бачить взагалі. Це найгірший клас вади: тихе псування даних.
 *
 * Тому плагін не лише малює приховані діапазони, а й коригує поведінку
 * курсора: ці три функції кажуть, КУДИ саме має піти позиція, щоб не
 * потрапити всередину прихованого тега.
 *
 * Діапазони (`from`/`to`) — абсолютні позиції документа ProseMirror, тобто ті
 * самі числа, з якими працює `EditorState.selection`.
 */

export interface HiddenRange {
  from: number;
  to: number;
}

/**
 * Позиція, винесена ЗА межі прихованого тега.
 *
 * Усередині діапазону (`from < pos < to`) повертає `to` — тобто каретка стає
 * одразу ПІСЛЯ тега. Це вибір, а не випадковість: на початок абзацу каретку
 * ставити небезпечно, бо між нею й текстом усе одно стоїть той самий
 * прихований тег, і набраний символ знову ліг би перед ним, а не туди, куди
 * автор дивиться.
 *
 * Межі лишаються як є: `pos === from` — це «перед тегом», `pos === to` —
 * «після тега». Обидві позиції нормальні, в них тег не псується.
 */
export function positionAfterHidden(pos: number, ranges: HiddenRange[]): number {
  for (const range of ranges) {
    if (pos > range.from && pos < range.to) return range.to;
  }
  return pos;
}

/**
 * Куди вставити набраний текст, якщо він мав замінити діапазон `[from, to)`.
 *
 * Випадок, який це рятує: автор виділив шматок тексту, у виділення попав
 * прихований тег, і автор почав набирати. Звичайна вставка знищила б тег —
 * мовчки, бо його не видно. Тут вставка йде ПІСЛЯ останнього перетнутого
 * тега, а тег лишається цілим.
 *
 * Якщо виділення прихованих тегів не торкається — повертається `from`, тобто
 * звичайна поведінка без жодних змін.
 */
export function textInsertionPoint(from: number, to: number, ranges: HiddenRange[]): number {
  let point = from;
  for (const range of ranges) {
    // Перетин «[from, to) × [range.from, range.to)» — звичайна умова для
    // напіввідкритих інтервалів; порожнє виділення (каретка) теж ловиться:
    // воно всередині, якщо from строго між межами діапазону.
    const overlaps = from < range.to && to > range.from;
    const caretInside = from === to && from > range.from && from < range.to;
    if (overlaps || caretInside) point = Math.max(point, range.to);
  }
  return point;
}
