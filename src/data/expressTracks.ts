/**
 * Реєстр напрямів експрес-майстра (Завдання 4).
 *
 * Навіщо реєстр, а не чотири кнопки в розмітці. Майстер «за 5 хвилин»
 * досі знав рівно один результат — книгу — і його кроки були вписані
 * константою просто в компонент. Щойно напрямів стає чотири, той самий
 * перелік знадобиться щонайменше у трьох місцях: екран вибору, смуга
 * кроків усередині майстра і те, що піде на сервер у чернетку. Перелік,
 * розмножений по трьох місцях, розходиться на першій же правці.
 *
 * Про чесність статусів. Гілка «Книга» працює — це наявний майстер.
 * Гілки 2-4 автор ще не описав, тому вони позначені `planned`, а їхні
 * кроки підписані як пропозиція, а не як реалізована поведінка. Це
 * навмисно: намалювати робочий на вигляд майстер, який нічого не робить,
 * гірше, ніж чесно сказати «чекає на опис» — людина інакше витратить час
 * на гілку, яка обірветься на другому кроці.
 */

export type ExpressTrackId = 'book' | 'course' | 'instruction' | 'game';

/** `ready` — гілка проходиться до кінця. `planned` — каркас без реалізації. */
export type ExpressTrackStatus = 'ready' | 'planned';

export interface ExpressTrack {
  id: ExpressTrackId;
  /** Порядковий номер із завдання — його видно на картці. */
  order: number;
  title: string;
  /** Один рядок: що це, якщо читати похапцем. */
  tagline: string;
  /** Що людина тримає в руках наприкінці. */
  outcome: string;
  status: ExpressTrackStatus;
  /**
   * Кроки майстра. Для `ready` — справжні кроки наявного майстра; для
   * `planned` — припущення про форму гілки, яке автор має підтвердити
   * або переписати. Інтерфейс підписує другий випадок окремо.
   */
  steps: string[];
}

