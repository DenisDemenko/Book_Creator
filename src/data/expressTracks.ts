export function findExpressTrack(id: string | null | undefined): ExpressTrack | undefined {
  return EXPRESS_TRACKS.find((t) => t.id === id);
}

/**
 * Чи можна одразу вести людину в майстер. Виділено окремою функцією, бо
 * перевірка потрібна і на екрані вибору, і при відновленні збереженого
 * напряму з localStorage: якщо гілку колись позначать `planned` назад
 * (наприклад, на час переробки), збережений вибір не має вести в нікуди.
 */
export function isTrackRunnable(id: string | null | undefined): boolean {
  return findExpressTrack(id)?.status === 'ready';
}
