/** Сутності вправи в порядку появи, без повторів і лише ті, що є в реєстрі. */
function knownEntities(slugs: string[] | undefined): string[] {
  const out: string[] = [];
  for (const slug of slugs || []) {
    const entity = entityBySlug(slug);
    if (entity && !out.includes(entity.slug)) out.push(entity.slug);
  }
  return out;
}

/** Набір сутностей тренажера — об’єднання сутностей його вправ. */
export function skillEntities(exercises: MicroExercise[]): string[] {
  return knownEntities(exercises.flatMap((ex) => ex.entities || []));
}

/**
 * Приєднує сутності до даних 18 навичок: доповнює наявні вправи кроком
 * розмітки, дописує нові вправи й рахує набір сутностей тренажера.
 * Вхідні об’єкти не змінюються — повертається нова копія.
 */
export function attachEntities(skills: SkillItem[]): SkillItem[] {
  return skills.map((skill) => {
    const existing = skill.microExercises.map((ex) => {
      const plan = EXERCISE_ENTITY_STEPS[ex.id];
      return plan ? { ...ex, entities: knownEntities(plan.entities), entityStep: plan.entityStep } : ex;
    });
    const added = (ENTITY_EXERCISES[skill.id] || []).map((ex) => ({ ...ex, entities: knownEntities(ex.entities) }));
    const microExercises = [...existing, ...added];
    return { ...skill, microExercises, entities: skillEntities(microExercises) };
  });
}
