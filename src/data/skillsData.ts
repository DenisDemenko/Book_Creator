// Helper: Calculate author rank and progress
export function getMasteryLevelInfo(xp: number) {
  const levels = [
    { level: 1, title: 'Початківець слова', minXp: 0, maxXp: 100 },
    { level: 2, title: 'Практик-новеліст', minXp: 100, maxXp: 300 },
    { level: 3, title: 'Майстер оповіді', minXp: 300, maxXp: 700 },
    { level: 4, title: 'Архітектор сюжетів', minXp: 700, maxXp: 1500 },
    { level: 5, title: 'Гросмейстер літератури', minXp: 1500, maxXp: 3000 },
  ];

  const current = levels.find(l => xp >= l.minXp && xp < l.maxXp) || levels[levels.length - 1];
  const next = levels.find(l => l.level === current.level + 1) || current;
  
  const xpInLevel = xp - current.minXp;
  const xpRequiredForNext = current.maxXp - current.minXp;
  const percentage = Math.min(100, Math.max(0, Math.round((xpInLevel / xpRequiredForNext) * 100)));

  return {
    level: current.level,
    title: current.title,
    currentXp: xp,
    nextLevelXp: current.maxXp,
    xpInLevel,
    xpRequiredForNext,
    percentage,
    isMaxLevel: current.level === 5
  };
}
