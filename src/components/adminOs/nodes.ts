/**
 * Реєстр вузлів адмінпанелі «Nova OS».
 *
 * Чому реєстр, а не розмітка. Нова панель має два режими показу тих самих
 * розділів: карта-постер (усі вузли одразу) і робоча консоль (один вузол +
 * інспектор). Тримати перелік двічі означало б, що додавши розділ, його
 * забудуть у другому місці — саме так і розходяться панелі. Тут перелік
 * один, обидва екрани читають його.
 *
 * `tab` — місток до наявного AdminPanelView: усі робочі панелі вже написані
 * й перевірені, нова сторінка їх ВБУДОВУЄ, а не переписує. Вузли без `tab`
 * (ключі API) відкриваються власним модальним вікном.
 */

import type { AdminTab } from '../AdminPanelView';

export type NodeAction = { kind: 'panel'; tab: AdminTab } | { kind: 'modal'; modal: 'api-keys' | 'prompts' };

export interface AdminNode {
  id: string;
  /** Коротка назва — на пігулці карти. */
  title: string;
  /** Що це таке, людською мовою — у пігулці другим рядком. */
  hint: string;
  /** Розгорнутий опис — в інспекторі вузла. */
  description: string;
  action: NodeAction;
  /** Група в лівій колонці консолі. */
  group: 'core' | 'operations';
}

