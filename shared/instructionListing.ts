/**
 * Назва інструкції у вітрині (журнал #556).
 *
 * РІШЕННЯ ВЛАСНИКА (12.11.2026): «інструкція іде на вітрину книгою під назвою
 * "Інструкція з ....."». Тобто окремого виду лістинга не завдумо — у вітрині
 * це книга, як і було, — але покупець має бачити з назви, що купує інструкцію,
 * а не повість. Доти в лістингу стояла назва самого виробу («Шафа Соло»), і
 * відрізнити інструкцію від книги з полиці було неможливо.
 *
 * ЧОМУ ПІДПИС ЖИВЕ В КНИЗІ, А НЕ НА СЕРВЕРІ. Формулювання «ІНСТРУКЦІЯ ЗІ
 * СКЛАДАННЯ» / «З ВИКОРИСТАННЯ» / «З ТЕХНІКИ БЕЗПЕКИ» вже є в каталозі типів
 * (`src/data/instructionTypes.ts`, поле `docBadge`) — там же, де підпис друку.
 * Сервер того каталогу не бачить, і копія на сервері розійшлася б з оригіналом
 * при першому ж новому типі. Тож книга, зроблена з інструкції, несе вже
 * готовий `badge`, а сервер лише складає назву.
 */

/** Слід інструкції в книзі: що це за тип, його підпис і назва самого виробу/процесу. */
export interface InstructionListingOrigin {
  /** `InstructionDocType` з каталогу типів: assembly, usage, safety, sequence… */
  docType: string;
  /** Підпис типу великими літерами, як у друку: «ІНСТРУКЦІЯ ЗІ СКЛАДАННЯ». */
  badge: string;
  /** Назва виробу, робіт або процесу — те, що автор написав у документі. */
  name: string;
}

/** «ІНСТРУКЦІЯ ЗІ СКЛАДАННЯ» → «Інструкція зі складання». */
export function instructionBadgeSentence(badge: string): string {
  const clean = badge.trim();
  if (!clean) return 'Інструкція';
  return clean.charAt(0).toUpperCase() + clean.slice(1).toLocaleLowerCase('uk-UA');
}

/**
 * Назва для вітрини. Якщо автор уже назвав документ «Інструкція…», другий раз
 * не підписуємо: «Інструкція зі складання: Інструкція зі складання шафи» —
 * саме та дурість, яку легко отримати автоматичним префіксом.
 */
export function instructionListingTitle(origin: InstructionListingOrigin): string {
  const name = (origin.name || '').trim();
  const sentence = instructionBadgeSentence(origin.badge);
  if (!name) return sentence;
  if (name.toLocaleLowerCase('uk-UA').startsWith('інструкц')) return name;
  return `${sentence}: ${name}`;
}
